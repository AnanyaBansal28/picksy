// Helper to generate 30 days of historical prices ending today
function generatePriceHistory(basePrices) {
  const dates = [];
  const today = new Date('2026-11-22');
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    // Pick or interpolate price from provided historical stages
    const progress = (29 - i) / 29;
    const priceIndex = Math.min(
      basePrices.length - 1,
      Math.floor(progress * basePrices.length)
    );
    const item = basePrices[priceIndex];
    
    dates.push({
      date: dateStr,
      price: item.price,
      note: item.note || 'Normal Listing',
    });
  }
  return dates;
}

